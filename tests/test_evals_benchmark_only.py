"""`openreading.evals` is a benchmark harness, not a dataset.

It ships scorers, a runner, a leaderboard, and exactly one synthetic sample case so the harness
can be smoke-tested offline. Labeled datasets — ground truth over real documents — are the
private asset (`internal/data/`, passed to `openreading leaderboard <dataset>` as a path) and
must never be committed here. This test is the tripwire: a real document or a second case
landing under `evals/sample/` fails `make verify` before it ships in a wheel.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

SAMPLE = Path(__file__).resolve().parent.parent / "src" / "openreading" / "evals" / "sample"

# The one synthetic case the harness needs to prove itself end to end.
ALLOWED_CASES = {"loan_page1"}
# A case is a `case.json` and, at most, tiny synthetic inputs. Real scans are orders of magnitude
# larger; 64 KiB is far above anything synthetic and far below any real document.
MAX_FILE_BYTES = 64 * 1024
DOCUMENT_SUFFIXES = {
    ".pdf",
    ".png",
    ".jpg",
    ".jpeg",
    ".tif",
    ".tiff",
    ".webp",
    ".bmp",
    ".gif",
    ".heic",
    ".heif",
    ".docx",
    ".doc",
    ".xlsx",
    ".xls",
    ".pptx",
    ".ppt",
}
# Committed document files anywhere under src/ or tests/ must be named here. Today there are
# none: the sample PDF is generated by `openreading.testing.sample_pdf`, and hosted-backend
# fixtures are captured JSON payloads, not documents.
ALLOWED_DOCUMENT_FILES: set[str] = set()


def test_sample_holds_only_the_synthetic_case():
    cases = sorted(p.name for p in SAMPLE.iterdir() if p.is_dir() and p.name != "__pycache__")
    assert set(cases) == ALLOWED_CASES, (
        f"evals/sample/ carries {cases}; the public harness ships one synthetic case only — "
        "labeled datasets go in internal/data/ (AGENTS.md: evals are a benchmark harness)"
    )
    loose = sorted(p.name for p in SAMPLE.iterdir() if p.is_file())
    assert loose == [], f"loose files under evals/sample/ (a labeled table?): {loose}"


def test_no_document_files_are_committed_under_src_or_tests():
    tracked = subprocess.run(
        ["git", "ls-files", "--", "src", "tests"],
        cwd=SAMPLE.parents[3],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    docs = sorted(f for f in tracked if Path(f).suffix.lower() in DOCUMENT_SUFFIXES)
    unexpected = [f for f in docs if f not in ALLOWED_DOCUMENT_FILES]
    assert unexpected == [], (
        "document files committed under src/ or tests/ — real documents and their labels live in "
        f"internal/data/, test inputs are generated or captured JSON: {unexpected}"
    )


def test_sample_contains_no_real_documents():
    offenders = []
    for p in SAMPLE.rglob("*"):
        if not p.is_file() or "__pycache__" in p.parts:
            continue
        if p.suffix.lower() in DOCUMENT_SUFFIXES:
            offenders.append(f"{p.relative_to(SAMPLE)} (document file)")
        elif p.stat().st_size > MAX_FILE_BYTES:
            offenders.append(f"{p.relative_to(SAMPLE)} ({p.stat().st_size} bytes)")
    assert offenders == [], "real documents / large files under evals/sample/: " + ", ".join(
        offenders
    )
